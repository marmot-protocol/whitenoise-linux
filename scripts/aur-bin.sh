#!/usr/bin/env bash
# Write the AUR package whitenoise-linux-bin for one release:
#
#   scripts/aur-bin.sh v2026.9.29-build.1 dist/WhiteNoise-v2026.9.29-build.1-archlinux-x86_64.tar.zst build/aur
#
# produces build/aur/whitenoise-linux-bin/PKGBUILD. The package installs the
# tarball scripts/arch-package.sh built for that tag, downloaded from the
# GitHub release. Its description, licenses, dependencies and conflicts are
# read from packaging/arch/whitenoise-linux-git/PKGBUILD, so the two packages
# cannot drift; only the version, source and checksum are the release's own.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
TAG="${1:?release tag required}"
TARBALL="${2:?release tarball required}"
OUT="${3:?output directory required}/whitenoise-linux-bin"

# Tags spell the revision as a pre-release (v2026.9.29-build.1); pkgver
# allows no hyphen, so it becomes 2026.9.29.1, which sorts below the -git
# package's 2026.9.29.1.r<count>.g<hash> builds of the same day.
if [[ ! "$TAG" =~ ^v([0-9]{4}\.[0-9]+\.[0-9]+)-build\.([0-9]+)$ ]]; then
  echo "Release tag must look like v2026.9.29-build.1, got '$TAG'" >&2
  exit 2
fi
PKGVER="${BASH_REMATCH[1]}.${BASH_REMATCH[2]}"
SHA="$(sha256sum "$TARBALL" | cut -d' ' -f1)"

# Only top-level assignments run; the build functions are never called.
source "$HERE/packaging/arch/whitenoise-linux-git/PKGBUILD"

mkdir -p "$OUT"
{
  cat <<EOF
# Maintainer: TBA
#
# Installs the release binary CI builds on Arch Linux with
# scripts/arch-package.sh. Generated by scripts/aur-bin.sh in
# $url;
# change that script or packaging/arch/whitenoise-linux-git/PKGBUILD there,
# not this file.
pkgname=whitenoise-linux-bin
pkgver=$PKGVER
pkgrel=1
pkgdesc=${pkgdesc@Q}
arch=(x86_64)
url=${url@Q}
license=(${license[*]@Q})
depends=(${depends[*]@Q})
optdepends=(
EOF
  printf '  %s\n' "${optdepends[@]@Q}"
  cat <<EOF
)
provides=(${provides[*]@Q})
conflicts=(${conflicts[*]@Q})
# Prebuilt: there is no debug information to split off.
options=(!debug)
source=("\$url/releases/download/$TAG/WhiteNoise-$TAG-archlinux-\$CARCH.tar.zst")
sha256sums=('$SHA')

package() {
  cp -a usr "\$pkgdir/"
  install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
  ln -s /usr/share/whitenoise-linux/licenses "\$pkgdir/usr/share/licenses/\$pkgname/bundled"
}
EOF
} > "$OUT/PKGBUILD"
printf 'Wrote %s\n' "$OUT/PKGBUILD"
